from datetime import datetime
from typing import Optional
from pydantic import BaseModel, ConfigDict, Field


# 1. Base schema: common attributes shared by creation and response
class HabitBase(BaseModel):
    title: str = Field(
        ..., 
        min_length=1, 
        max_length=100, 
        description="Title of the habit (e.g., 'Morning Meditation')"
    )
    description: Optional[str] = Field(
        None, 
        max_length=500, 
        description="Optional details or instructions for this habit"
    )


# 2. Creation schema: payload required to create a new habit
class HabitCreate(HabitBase):
    pass  # Needs only title and description; id and timestamps are generated by server/DB


# 3. Update schema: optional fields for updating an existing habit
class HabitUpdate(BaseModel):
    title: Optional[str] = Field(None, min_length=1, max_length=100)
    description: Optional[str] = Field(None, max_length=500)
    is_active: Optional[bool] = None


# 4. Response schema: what the API returns back to the client
class HabitResponse(HabitBase):
    id: int
    is_active: bool
    created_at: datetime

    # Pydantic v2 ORM configuration
    model_config = ConfigDict(from_attributes=True)